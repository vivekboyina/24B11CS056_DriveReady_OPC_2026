"""### Define Data, the Order Model, and Tools
We define the `Order` schema using Pydantic and create tools for looking up book prices (handling the discount rule: buy 5 rule books, get 1 free), checking operating hours, and logging orders.
"""

from typing import Literal
from pydantic import BaseModel, Field
from langchain.tools import tool

MENU = {"white book": 50, "rule book": 50, "pencil": 5}
HOURS = {"monday": "9 am to 8 pm", "tuesday": "9 am to 8 pm", "wednesday": "9 am to 8 pm",
         "thursday": "9 am to 8 pm", "friday": "9 am to 8 pm", "saturday": "9 am to 8 pm",
         "sunday": "10 am to 5 pm"}

class BookOrder(BaseModel):
    """A book order taken from a customer's chat message."""
    name: str = Field(description="Customer's first name")
    item: Literal["white book", "rule book", "pencil"] = Field(description="Menu item")
    qty: int = Field(description="How many", ge=1)
    date: str = Field(description="Pickup/delivery date as the customer said it")

@tool
def get_price(item: str, qty: int = 1) -> str:
    """Get the total price in rupees for a quantity of one menu item from Knowledge Book Store.

    Args:
        item: Menu item, e.g. "white book", "rule book", or "pencil"
        qty: How many the customer wants
    """
    normalized_item = item.lower().strip()
    price = MENU.get(normalized_item)
    if price is None:
        return f"'{item}' is not on our menu. We have: {', '.join(MENU)}."

    # Apply the special discount: Buy 5 rule books, get 1 free
    if normalized_item == "rule book" and qty >= 6:
        free_books = qty // 6
        billable_qty = qty - free_books
        total_price = billable_qty * price
        return f"{qty} x {item} = Rs {total_price} (includes {free_books} free book(s) via Buy 5 Get 1 Free promotion!)"

    return f"{qty} x {item} = Rs {price * qty}"

@tool
def is_open(day: str) -> str:
    """Check the book store's opening hours for a day of the week, e.g. "sunday"."""
    hours = HOURS.get(day.lower().strip())
    return f"Open {hours} on {day}." if hours else f"'{day}' is not a valid day."

@tool
def log_order(name: str, item: str, qty: int, date: str) -> str:
    """Save a confirmed book order to the Google sheet.
    Use only when the customer has explicitly given their name, item, quantity, and date."""
    try:
        order = BookOrder(name=name, item=item.lower().strip(), qty=qty, date=date)
    except Exception as e:
        return f"Could not save the order: {e}. Please ask the customer to clarify details."

    # Calculate price including discount
    price = MENU[order.item]
    if order.item == "rule book" and order.qty >= 6:
        free_books = order.qty // 6
        billable_qty = order.qty - free_books
        total = billable_qty * price
    else:
        total = price * order.qty

    ws.append_row([order.name, order.item, order.qty, order.date, total])
    return f"Saved: {order.qty} x {order.item} for {order.name} on {order.date}, Rs {total}."

