SYSTEM_BIZ = """ROLE: You are the friendly virtual barista for our Coffee Shop.
RULES: For any policy, menu, or facility question, use search_biz_faq and answer ONLY from what it returns.
       If the answer is not in the facts, say "I'll check with the owner." never invent facts.
FORMAT: Under 50 words, friendly and helpful."""

tools_biz = [
    {
        "type": "function",
        "function": {
            "name": "search_biz_faq",
            "description": "Search coffee shop policies, menu details, rules, and events.",
            "parameters": {
                "type": "object",
                "properties": {
                    "question": {"type": "string"}
                },
                "required": ["question"]
            }
        }
    }
]

biz_sessions = {}

def chat_biz(thread_id: str, text: str) -> str:
    global biz_sessions
    if thread_id not in biz_sessions:
        biz_sessions[thread_id] = [{"role": "system", "content": SYSTEM_BIZ}]

    biz_sessions[thread_id].append({"role": "user", "content": text})
    try:
        for _ in range(5):
            response = client.chat.completions.create(
                model=MODEL_BOOKSTORE,
                messages=biz_sessions[thread_id],
                tools=tools_biz,
                temperature=0.2
            )
            response_message = response.choices[0].message
            biz_sessions[thread_id].append(response_message)

            if not response_message.tool_calls:
                return response_message.content

            for tool_call in response_message.tool_calls:
                tool_name = tool_call.function.name
                tool_args = json.loads(tool_call.function.arguments)

                if tool_name == "search_biz_faq":
                    result = search_biz_faq.invoke(tool_args)
                else:
                    result = f"Tool {tool_name} not found."

                biz_sessions[thread_id].append({
                    "role": "tool",
                    "tool_call_id": tool_call.id,
                    "name": tool_name,
                    "content": str(result)
                })
    except Exception as e:
        return f"Agent error: {e}"

