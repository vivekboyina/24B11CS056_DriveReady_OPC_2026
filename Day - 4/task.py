# Initialize the native Groq client
client = Groq(api_key=userdata.get("Agentic_AI"))
MODEL_BOOKSTORE = "openai/gpt-oss-20b"

SYSTEM_BOOKSTORE = """ROLE:   You are the friendly order assistant for Knowledge book store.
FACTS:  Orders need 24 hours' notice. All orders get a call before delivering to confirm it.
        DISCOUNT: Buy 5 rule books, get 1 free (6 rule books cost 250 rupees instead of 300).
RULES:  Always use get_price for prices and is_open for timings; never guess them.
        Before log_order, make sure you have name, item, quantity and date; ask if missing.
        After saving, read the order back with the total.
FORMAT: Under 60 words, friendly, English or Telugu matching the customer."""

# Schema configuration for Groq tools support
tools = [
    {
        "type": "function",
        "function": {
            "name": "get_price",
            "description": "Get the total price in rupees for a quantity of one menu item from Knowledge Book Store.",
            "parameters": {
                "type": "object",
                "properties": {
                    "item": {"type": "string", "description": "Menu item, e.g. white book, rule book, or pencil"},
                    "qty": {"type": "integer", "default": 1, "description": "How many the customer wants"}
                },
                "required": ["item"]
            }
        }
    },
    {
        "type": "function",
        "function": {
            "name": "is_open",
            "description": "Check the book store's opening hours for a day of the week, e.g. sunday.",
            "parameters": {
                "type": "object",
                "properties": {
                    "day": {"type": "string", "description": "Day of the week"}
                },
                "required": ["day"]
            }
        }
    },
    {
        "type": "function",
        "function": {
            "name": "log_order",
            "description": "Save a confirmed book order to the Google sheet. Use only when the customer has explicitly given their name, item, quantity, and date.",
            "parameters": {
                "type": "object",
                "properties": {
                    "name": {"type": "string"},
                    "item": {"type": "string"},
                    "qty": {"type": "integer"},
                    "date": {"type": "string"}
                },
                "required": ["name", "item", "qty", "date"]
            }
        }
    }
]

history = [{"role": "system", "content": SYSTEM_BOOKSTORE}]

def chat(text: str) -> str:
    global history
    history.append({"role": "user", "content": text})
    try:
        for _ in range(5):
            response = client.chat.completions.create(
                model=MODEL_BOOKSTORE,
                messages=history,
                tools=tools,
                temperature=0.2
            )
            response_message = response.choices[0].message
            history.append(response_message)

            if not response_message.tool_calls:
                return response_message.content

            for tool_call in response_message.tool_calls:
                tool_name = tool_call.function.name
                tool_args = json.loads(tool_call.function.arguments)

                if tool_name == "get_price":
                    result = get_price.invoke(tool_args)
                elif tool_name == "is_open":
                    result = is_open.invoke(tool_args)
                elif tool_name == "log_order":
                    result = log_order.invoke(tool_args)
                else:
                    result = f"Tool {tool_name} not found."

                history.append({
                    "role": "tool",
                    "tool_call_id": tool_call.id,
                    "name": tool_name,
                    "content": str(result)
                })
    except Exception as e:
        print("Agent error:", e)
        return "Sorry, I'm a little busy. Please try again in a minute."

