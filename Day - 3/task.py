from langchain_groq import ChatGroq
llm = ChatGroq(model="openai/gpt-oss-20b", temperature=0.3)

import json
from langchain_core.prompts import ChatPromptTemplate, MessagesPlaceholder
from langchain_core.output_parsers import StrOutputParser

MENU = {"white book": 50, "rule book": 50, "pencil": 5}
menu_str = json.dumps(MENU).replace("{", "{{").replace("}", "}}")

SYSTEM = f"""ROLE:   You are the friendly assistant for Knowledge book store.
FACTS:  Menu with prices in rupees: {menu_str}
        Orders need 24 hours' notice. All orders get a call before delivering to confirm it.
        DISCOUNT: Buy 5 rule books, get 1 free (6 rule books cost 250 rupees instead of 300).
RULES:  Never promise a delivery time. If it isn't in FACTS, say \"I'll check with the owner.\"
        Remember the customer's name and order during the chat.
        When mentioning notice, always write exactly \"24 hours\".
FORMAT: Under 50 words, friendly, English or Telugu matching the customer."""

prompt = ChatPromptTemplate.from_messages([
    ("system", SYSTEM),
    MessagesPlaceholder("history"),
    ("human", "{question}"),
])
chain = prompt | llm | StrOutputParser()

history = []
def ask(question: str) -> str:
    answer = chain.invoke({"history": history, "question": question})
    history.extend([("human", question), ("ai", answer)])
    return answer

print(ask("Hi, I'm Vivek. Do you have rule books?"))
print(ask("What's my name?"))

